"""## 11. Parse Sentinel-2 patches and compute spectral indices

Reconstructs the five exported Sentinel-2 bands as 50 × 50 arrays, identifies valid pixels, computes four spectral indices, and combines all features into a nine-channel patch.

The GEE export stores only B2, B3, B4, B8, and B11 as 50×50 arrays. The spectral indices are computed here:

- NDVI = (B8 − B4) / (B8 + B4)
- NDWI = (B3 − B8) / (B3 + B8)
- NDBI = (B11 − B8) / (B11 + B8)
- NDMI = (B8 − B11) / (B8 + B11)
"""

S2_STRING_KEYS = ['patch_id', 'split', 'region_name', 'patch_group', 'dominant_class_name', 'date', 's2_id']
S2_NUMERIC_KEYS = [
    'center_lon', 'center_lat', 'inside_fraction',
    'tree_pixel_count', 'shrub_pixel_count', 'grass_pixel_count', 'crop_pixel_count', 'built_pixel_count',
    'ignored_pixel_count', 'selected_pixel_count', 'total_pixel_count',
    'tree_fraction', 'shrub_fraction', 'grass_fraction', 'crop_fraction', 'built_fraction', 'selected_fraction',
    'dominant_id', 'dominant_esa_code', 'dominant_fraction',
    'time_start', 'doy', 'month', 'cloud_pct'
]


def safe_divide(num, den, eps=1e-6):
    return num / (den + eps)


def compute_indices(arr5):
    # arr5 shape: [H, W, 5] in B2, B3, B4, B8, B11 order.
    b2 = arr5[..., 0]
    b3 = arr5[..., 1]
    b4 = arr5[..., 2]
    b8 = arr5[..., 3]
    b11 = arr5[..., 4]

    nodata_mask = np.any(arr5 == NO_DATA_VALUE, axis=-1)

    ndvi = safe_divide(b8 - b4, b8 + b4)
    ndwi = safe_divide(b3 - b8, b3 + b8)
    ndbi = safe_divide(b11 - b8, b11 + b8)
    ndmi = safe_divide(b8 - b11, b8 + b11)

    idx = np.stack([ndvi, ndwi, ndbi, ndmi], axis=-1).astype(np.float32)
    idx[nodata_mask] = NO_DATA_VALUE
    return idx


def parse_s2_example(raw):
    feature_spec = {}
    for b in S2_BANDS:
        feature_spec[b] = tf.io.VarLenFeature(tf.float32)
    for k in S2_STRING_KEYS:
        feature_spec[k] = tf.io.VarLenFeature(tf.string)
    for k in S2_NUMERIC_KEYS:
        feature_spec[k] = tf.io.VarLenFeature(tf.float32)

    parsed = tf.io.parse_single_example(raw, feature_spec)

    item = {}
    for k in S2_STRING_KEYS:
        item[k] = bytes_to_str(sparse_first(parsed, k))
    for k in S2_NUMERIC_KEYS:
        v = sparse_first(parsed, k)
        item[k] = float(v.numpy()) if v is not None else np.nan

    band_arrays = []
    for band in S2_BANDS:
        vec = tf.sparse.to_dense(parsed[band]).numpy()
        if vec.size != PATCH_SIZE * PATCH_SIZE:
            raise ValueError(f'Unexpected {band} length for {item.get("patch_id")}: {vec.size}')
        band_arrays.append(vec.reshape(PATCH_SIZE, PATCH_SIZE).astype(np.float32))

    arr5 = np.stack(band_arrays, axis=-1)  # [H, W, 5]
    valid_mask = np.all(arr5 != NO_DATA_VALUE, axis=-1)
    valid_fraction = float(valid_mask.mean())

    idx = compute_indices(arr5)
    arr9 = np.concatenate([arr5, idx], axis=-1).astype(np.float32)

    item['array_5band'] = arr5
    item['array_9band'] = arr9
    item['valid_mask'] = valid_mask
    item['valid_fraction_colab'] = valid_fraction
    return item

