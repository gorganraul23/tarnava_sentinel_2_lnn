"""## 16. Build quality-controlled patch time-series tensors

Reconstructs chronological 50 × 50 Sentinel-2 sequences for each eligible patch and aligns them with the corresponding ESA WorldCover label map. Records below the valid-pixel threshold are excluded, while duplicate patch-date observations are resolved by retaining the record with the highest valid coverage.

The output contains spectral features, temporal masks, pixel-validity masks, acquisition intervals, labels, dates, and patch identifiers.

Output shape:

```python
X:      [N, T, 50, 50, 9]
y:      [N, 50, 50]
mask_t: [N, T]
delta:  [N, T, 1]
```
"""

def iter_s2_items_for_split(split, months=None):
    months = MONTHS if months is None else months
    for month in months:
        files, mode = files_for_split_month(split, month)
        for path in files:
            for raw in tfrecord_dataset([path]):
                item = parse_s2_example(raw)
                if item['split'] == split:
                    yield item


def build_split_tensor(
    split,
    months=None,
    patch_ids=None,
    min_valid_fraction=MIN_VALID_FRACTION,
    max_dates=None,
    max_patches=None,
):
    if not labels_by_patch:
        raise RuntimeError('Load label patches before building tensors.')

    months = MONTHS if months is None else months

    # Collect best item per patch_id + date.
    best = {}
    for item in iter_s2_items_for_split(split, months=months):
        pid = item['patch_id']
        if patch_ids is not None and pid not in patch_ids:
            continue
        if item['valid_fraction_colab'] < min_valid_fraction:
            continue
        key = (pid, item['date'])
        old = best.get(key)
        if old is None or item['valid_fraction_colab'] > old['valid_fraction_colab']:
            best[key] = item

    if not best:
        raise RuntimeError(f'No usable S2 records found for split={split}, months={months}')

    # Determine patch list and date list.
    patch_list = sorted({pid for pid, date in best.keys() if pid in labels_by_patch})
    if max_patches is not None:
        patch_list = patch_list[:max_patches]

    date_list = sorted({date for pid, date in best.keys() if pid in patch_list})
    if max_dates is not None:
        date_list = date_list[:max_dates]

    N = len(patch_list)
    T = len(date_list)
    H = W = PATCH_SIZE
    C = len(ALL_FEATURE_BANDS)

    X = np.zeros((N, T, H, W, C), dtype=np.float32)
    valid_pixel_mask = np.zeros((N, T, H, W), dtype=bool)
    time_mask = np.zeros((N, T), dtype=np.float32)
    observation_valid_fraction = np.zeros((N, T), dtype=np.float32)
    delta_days = np.zeros((N, T, 1), dtype=np.float32)
    y = np.zeros((N, H, W), dtype=np.int16)

    date_to_idx = {d: i for i, d in enumerate(date_list)}

    for i, pid in enumerate(patch_list):
        y[i] = labels_by_patch[pid]
        last_date = None
        for date in date_list:
            item = best.get((pid, date))
            if item is None:
                continue
            t = date_to_idx[date]
            arr = item['array_9band']
            X[i, t] = arr
            valid_pixel_mask[i, t] = np.all(arr[..., :5] != NO_DATA_VALUE, axis=-1)
            time_mask[i, t] = 1.0
            observation_valid_fraction[i, t] = item['valid_fraction_colab']

            current_date = pd.to_datetime(date)
            if last_date is None:
                delta_days[i, t, 0] = 0.0
            else:
                delta_days[i, t, 0] = (current_date - last_date).days
            last_date = current_date

    # Replace NO_DATA_VALUE with 0 after masks are stored.
    X[X == NO_DATA_VALUE] = 0.0
    n_observations = time_mask.sum(axis=1).astype(np.int16)

    return {
        'X': X,
        'y': y,
        'time_mask': time_mask,
        'valid_pixel_mask': valid_pixel_mask,
        'observation_valid_fraction': observation_valid_fraction,
        'delta_days': delta_days,
        'n_observations': n_observations,
        'patch_ids': np.array(patch_list),
        'dates': np.array(date_list),
        'bands': np.array(ALL_FEATURE_BANDS),
    }

