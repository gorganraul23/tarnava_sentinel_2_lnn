"""### 19.6 — Build and save the 2024 Region B tensor

Constructs the March–November 2024 Sentinel-2 time series for the exact 30
Region B patches used in the 2023 test set. The same 2023 ESA WorldCover
reference maps are reused, while Sentinel-2 observations are independently
quality filtered for 2024.

The cache structure is identical to the model-ready 2023 test cache.
"""

# -------------------------------------------------------
# 19.6 Build the complete 2024 Region B tensor
# -------------------------------------------------------

def iter_2024_test_items():
    """
    Yield all Sentinel-2 records from the complete
    March-November 2024 Region B exports.
    """

    for month in MONTHS_2024:

        files, mode = (
            files_for_2024_test_month(
                month
            )
        )

        if mode not in {
            'full_test_month',
            'complete_group_month'
        }:
            raise RuntimeError(
                f'Incomplete 2024 month {month}: {mode}'
            )

        for path in files:

            for raw in tfrecord_dataset(
                [path]
            ):

                item = parse_s2_example(
                    raw
                )

                if item['split'] != 'test':
                    raise RuntimeError(
                        'Unexpected split in 2024 export: '
                        f"{item['split']}"
                    )

                yield item


def build_2024_test_tensor(
    min_valid_fraction=MIN_VALID_FRACTION
):
    """
    Construct the complete 2024 Region B temporal-transfer
    dataset using the frozen 2023 Region B reference labels.
    """

    # ---------------------------------------------------
    # Keep the best observation for each patch + date
    # ---------------------------------------------------

    best = {}

    expected_patch_set = set(
        reference_patch_ids
    )

    for item in iter_2024_test_items():

        patch_id = item[
            'patch_id'
        ]

        if patch_id not in expected_patch_set:
            raise RuntimeError(
                'Unexpected 2024 patch ID: '
                f'{patch_id}'
            )

        if (
            item['valid_fraction_colab']
            < min_valid_fraction
        ):
            continue

        key = (
            patch_id,
            item['date']
        )

        old_item = best.get(
            key
        )

        if (
            old_item is None
            or
            item['valid_fraction_colab']
            >
            old_item['valid_fraction_colab']
        ):
            best[key] = item


    if not best:
        raise RuntimeError(
            'No usable 2024 observations found.'
        )


    # ---------------------------------------------------
    # Preserve exact 2023 Region B patch order
    # ---------------------------------------------------

    patch_list = (
        reference_patch_ids.tolist()
    )


    # Global temporal axis across the 30 patches.
    date_list = sorted({
        date
        for patch_id, date
        in best.keys()
    })


    N = len(
        patch_list
    )

    T = len(
        date_list
    )

    H = W = PATCH_SIZE

    C = len(
        ALL_FEATURE_BANDS
    )


    print(
        '2024 tensor dimensions:'
    )

    print(
        'N patches:',
        N
    )

    print(
        'T unique usable dates:',
        T
    )

    print(
        'Channels:',
        C
    )


    # ---------------------------------------------------
    # Allocate arrays
    # ---------------------------------------------------

    X = np.zeros(
        (
            N,
            T,
            H,
            W,
            C
        ),
        dtype=np.float32
    )

    y = (
        reference_labels
        .astype(
            np.int16,
            copy=True
        )
    )

    time_mask = np.zeros(
        (
            N,
            T
        ),
        dtype=np.float32
    )

    valid_pixel_mask = np.zeros(
        (
            N,
            T,
            H,
            W
        ),
        dtype=bool
    )

    observation_valid_fraction = (
        np.zeros(
            (
                N,
                T
            ),
            dtype=np.float32
        )
    )

    delta_days = np.zeros(
        (
            N,
            T,
            1
        ),
        dtype=np.float32
    )


    date_to_index = {
        date: index
        for index, date
        in enumerate(date_list)
    }


    # ---------------------------------------------------
    # Populate patch sequences
    # ---------------------------------------------------

    for patch_index, patch_id in enumerate(
        patch_list
    ):

        last_date = None

        patch_observation_count = 0


        for date in date_list:

            item = best.get(
                (
                    patch_id,
                    date
                )
            )

            if item is None:
                continue


            time_index = (
                date_to_index[
                    date
                ]
            )


            arr = item[
                'array_9band'
            ]


            if arr.shape != (
                PATCH_SIZE,
                PATCH_SIZE,
                len(
                    ALL_FEATURE_BANDS
                )
            ):
                raise RuntimeError(
                    'Unexpected 2024 array shape '
                    f'for {patch_id} on {date}: '
                    f'{arr.shape}'
                )


            X[
                patch_index,
                time_index
            ] = arr


            valid_pixel_mask[
                patch_index,
                time_index
            ] = item[
                'valid_mask'
            ]


            time_mask[
                patch_index,
                time_index
            ] = 1.0


            observation_valid_fraction[
                patch_index,
                time_index
            ] = item[
                'valid_fraction_colab'
            ]


            current_date = (
                pd.to_datetime(
                    date
                )
            )


            if last_date is None:

                delta_days[
                    patch_index,
                    time_index,
                    0
                ] = 0.0

            else:

                delta_days[
                    patch_index,
                    time_index,
                    0
                ] = (
                    current_date
                    - last_date
                ).days


            last_date = (
                current_date
            )

            patch_observation_count += 1


        if patch_observation_count == 0:

            raise RuntimeError(
                'No usable 2024 observations '
                f'for patch {patch_id}.'
            )


    # ---------------------------------------------------
    # Replace NO_DATA with zero only after masks exist
    # ---------------------------------------------------

    X[
        X == NO_DATA_VALUE
    ] = 0.0


    n_observations = (
        time_mask
        .sum(
            axis=1
        )
        .astype(
            np.int16
        )
    )


    return {
        'X':
            X,

        'y':
            y,

        'time_mask':
            time_mask,

        'valid_pixel_mask':
            valid_pixel_mask,

        'observation_valid_fraction':
            observation_valid_fraction,

        'delta_days':
            delta_days,

        'n_observations':
            n_observations,

        'patch_ids':
            np.array(
                patch_list
            ),

        'dates':
            np.array(
                date_list
            ),

        'bands':
            np.array(
                ALL_FEATURE_BANDS
            )
    }


