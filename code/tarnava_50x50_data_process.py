"""## 18. Load cached datasets for PyTorch

Loads a model-ready `.npz` cache as a PyTorch Dataset. Each sample contains a chronological Sentinel-2 sequence, the corresponding 50 × 50 ESA WorldCover label map, temporal and pixel-validity masks, acquisition intervals, observation-quality values, and patch metadata.

The Sentinel-2 tensor is returned in channel-first format:

```python
X: [T, 9, 50, 50]
y: [50, 50]
```
"""

import torch
from torch.utils.data import Dataset, DataLoader


class TarnavaPatchTimeSeriesDataset(Dataset):
    def __init__(self, npz_path):
        data = np.load(npz_path, allow_pickle=False)

        # Stored cache shape: [N, T, H, W, C]
        self.X = torch.from_numpy(
            data['X'].astype(np.float32, copy=False)
        )

        # Pixel-level ESA WorldCover labels: [N, H, W]
        self.y = torch.from_numpy(
            data['y'].astype(np.int64, copy=False)
        )

        self.time_mask = torch.from_numpy(
            data['time_mask'].astype(np.float32, copy=False)
        )

        self.valid_pixel_mask = torch.from_numpy(
            data['valid_pixel_mask'].astype(bool, copy=False)
        )

        self.delta_days = torch.from_numpy(
            data['delta_days'].astype(np.float32, copy=False)
        )

        if 'observation_valid_fraction' in data.files:
            self.observation_valid_fraction = torch.from_numpy(
                data['observation_valid_fraction'].astype(
                    np.float32,
                    copy=False
                )
            )
        else:
            self.observation_valid_fraction = self.time_mask.clone()

        if 'n_observations' in data.files:
            self.n_observations = torch.from_numpy(
                data['n_observations'].astype(
                    np.int64,
                    copy=False
                )
            )
        else:
            self.n_observations = self.time_mask.sum(dim=1).long()

        self.patch_ids = data['patch_ids']
        self.dates = data['dates']
        self.bands = data['bands']

    def __len__(self):
        return self.X.shape[0]

    def __getitem__(self, idx):
        # Convert [T, H, W, C] to [T, C, H, W].
        x = self.X[idx].permute(0, 3, 1, 2)

        y = self.y[idx]

        return {
            'X': x,
            'y': y,

            # Exclude unsupported WorldCover pixels from the loss.
            'label_mask': y != 255,

            # Available acquisition dates.
            'time_mask': self.time_mask[idx],

            # Valid pixels within each acquisition.
            'valid_pixel_mask': self.valid_pixel_mask[idx],

            # Fraction of valid pixels per acquisition.
            'observation_valid_fraction':
                self.observation_valid_fraction[idx],

            # Days since the previous usable acquisition.
            'delta_days': self.delta_days[idx],

            'n_observations': self.n_observations[idx],
            'patch_id': str(self.patch_ids[idx]),
        }


