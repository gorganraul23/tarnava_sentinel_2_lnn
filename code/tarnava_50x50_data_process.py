"""## 5. TFRecord utilities

Defines functions for inspecting and decoding Earth Engine TFRecord files.

- inspects one record to identify its fields and data types;
- reads scalar metadata and flattened array properties;
- uses VarLenFeature because Earth Engine stores arrays as variable-length features;
- converts TensorFlow sparse values into NumPy arrays;
- decodes text fields such as patch_id, split, and date;
- prepares the arrays for reconstruction into 50 × 50 patches.
"""

def tfrecord_dataset(paths, compression_type=None):
    if isinstance(paths, (str, Path)):
        paths = [str(paths)]
    else:
        paths = [str(p) for p in paths]

    if compression_type is None:
        # Earth Engine sometimes writes .tfrecord, sometimes .tfrecord.gz.
        # Use GZIP only if all paths end with .gz.
        compression_type = 'GZIP' if all(str(p).endswith('.gz') for p in paths) else ''
    return tf.data.TFRecordDataset(paths, compression_type=compression_type)


def inspect_tfrecord(paths, max_records=1):
    ds = tfrecord_dataset(paths)
    out = []
    for i, raw in enumerate(ds.take(max_records)):
        ex = tf.train.Example()
        ex.ParseFromString(raw.numpy())
        rows = []
        for key, feat in sorted(ex.features.feature.items()):
            kind = feat.WhichOneof('kind')
            if kind == 'float_list':
                n = len(feat.float_list.value)
                preview = list(feat.float_list.value[:5])
            elif kind == 'int64_list':
                n = len(feat.int64_list.value)
                preview = list(feat.int64_list.value[:5])
            elif kind == 'bytes_list':
                n = len(feat.bytes_list.value)
                preview = [v[:50] for v in feat.bytes_list.value[:3]]
            else:
                n = 0
                preview = []
            rows.append({'key': key, 'kind': kind, 'length': n, 'preview': preview})
        out.append(pd.DataFrame(rows))
    return out[0] if out else pd.DataFrame()


def get_example_count(paths):
    count = 0
    for _ in tfrecord_dataset(paths):
        count += 1
    return count

