def sparse_first(parsed, key, default=None):
    if key not in parsed:
        return default
    dense = tf.sparse.to_dense(parsed[key])
    if dense.shape[0] == 0:
        return default
    return dense[0]


def bytes_to_str(x):
    if x is None:
        return None
    if isinstance(x, bytes):
        return x.decode('utf-8')
    if hasattr(x, 'numpy'):
        v = x.numpy()
        if isinstance(v, bytes):
            return v.decode('utf-8')
        return str(v)
    return str(x)


def parse_label_example(raw):
    feature_spec = {
        'label_id': tf.io.VarLenFeature(tf.float32),
        'esa_label': tf.io.VarLenFeature(tf.float32),
    }
    for k in LABEL_STRING_KEYS:
        feature_spec[k] = tf.io.VarLenFeature(tf.string)
    for k in LABEL_NUMERIC_KEYS:
        feature_spec[k] = tf.io.VarLenFeature(tf.float32)

    parsed = tf.io.parse_single_example(raw, feature_spec)

    patch_id = bytes_to_str(sparse_first(parsed, 'patch_id'))
    split = bytes_to_str(sparse_first(parsed, 'split'))
    patch_group = bytes_to_str(sparse_first(parsed, 'patch_group'))

    label_vec = tf.sparse.to_dense(parsed['label_id']).numpy()
    if label_vec.size != PATCH_SIZE * PATCH_SIZE:
        raise ValueError(f'Unexpected label_id length for {patch_id}: {label_vec.size}')

    label_arr = label_vec.reshape(PATCH_SIZE, PATCH_SIZE).astype(np.int16)

    item = {
        'patch_id': patch_id,
        'split': split,
        'patch_group': patch_group,
        'label_id': label_arr,
    }

    if 'esa_label' in parsed:
        esa_vec = tf.sparse.to_dense(parsed['esa_label']).numpy()
        if esa_vec.size == PATCH_SIZE * PATCH_SIZE:
            item['esa_label'] = esa_vec.reshape(PATCH_SIZE, PATCH_SIZE).astype(np.int16)

    return item


